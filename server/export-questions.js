/* ============================================================================
   G.O.C Academy Hub — export the question bank as SQL
   ----------------------------------------------------------------------------
   The questions live in js/goc-core.js so that the browser demo, the Node
   server and the database all use one copy. When you set up a fresh Supabase
   project, run this to turn that copy into inserts:

       node server/export-questions.js > server/questions.sql

   Then paste the output into the Supabase SQL editor after schema.sql.
   ========================================================================== */
'use strict';

const core = require('../js/goc-core.js');

function q(value) {
  if (value == null) return 'null';
  return "'" + String(value).replace(/'/g, "''") + "'";
}
function arr(list) {
  if (!list || !list.length) return 'null';
  return 'array[' + list.map(q).join(',') + ']';
}

const rows = core.seedQuestions();

console.log('-- Generated by server/export-questions.js from js/goc-core.js');
console.log('-- ' + rows.length + ' questions. Safe to re-run: it clears the bank first.');
console.log('delete from questions;');
console.log('insert into questions');
console.log('  (subject, topic, kind, section, period, body, options, answer_index, expected, max_mark, difficulty, explanation, is_active)');
console.log('values');

console.log(rows.map(r => '  (' + [
  q(r.subject), q(r.topic), q(r.kind), q(r.section), q(r.period), q(r.text),
  arr(r.options), r.kind === 'objective' ? Number(r.answer) : 'null',
  r.kind === 'theory' ? q(r.expected) : 'null',
  Number(r.maxMark) || 1, q(r.difficulty), q(r.explanation || ''),
  r.active ? 'true' : 'false'
].join(', ') + ')').join(',\n') + ';');
